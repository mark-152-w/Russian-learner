// Generate TypeScript types from schemas/*.schema.json → src/types/content.gen.ts
// All schemas are compiled through one root so shared $defs become one declaration each.
import { compile } from 'json-schema-to-typescript'
import { readdirSync, writeFileSync } from 'node:fs'

const files = readdirSync('schemas').filter((f) => f.endsWith('.schema.json') && f !== 'common.schema.json')
const root = {
  title: 'ContentFiles',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(files.map((f) => [f.replace('.schema.json', ''), { $ref: f }])),
}
const ts = await compile(root, 'ContentFiles', {
  cwd: 'schemas',
  bannerComment: '/* Generated by scripts/gen-types.mjs from schemas/. Do not edit. */',
  additionalProperties: false,
  style: { singleQuote: true, semi: false },
})
writeFileSync('src/types/content.gen.ts', ts)
console.log('wrote src/types/content.gen.ts')
